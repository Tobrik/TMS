export type ChatStringKey = keyof (typeof chatStrings)["ru"];

export function tc(key: ChatStringKey, lang: Lang = "ru", vars?: Record<string, string | number>): string {
  let text: string = chatStrings[lang]?.[key] ?? chatStrings.ru[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
  }
  return text;
}
